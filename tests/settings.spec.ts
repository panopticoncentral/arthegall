import { expect, test } from '@playwright/test';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createServer } from '../apps/server/src/server.js';
import { ServerStore } from '../apps/server/src/store.js';
import { availablePort } from './helpers/port.js';
import { reportingUpgrade } from './helpers/reporting-upgrade.js';

test('reporting settings share revisions and approvals with the DM and preserve its draft', async ({page}, info) => {
  const root = mkdtempSync(join(tmpdir(),'arthegall-settings-'));
  const prior = await reportingUpgrade(root);
  const store = new ServerStore(prior.serverPath);
  const port = await availablePort(), origin = 'http://127.0.0.1:' + port;
  const app = await createServer(store,origin,resolve('dist/web'));
  try {
    await app.listen({host:'127.0.0.1',port});
    await page.context().addCookies([{url:origin,name:'arthegall',value:prior.browserToken,httpOnly:true}]);
    await page.goto(origin);
    await page.getByRole('button',{name:'Settings',exact:true}).click();
    await expect(page.getByRole('heading',{name:'System settings'})).toBeVisible();
    await page.screenshot({path:info.outputPath('system.png')});
    await page.getByRole('link',{name:'Agents',exact:true}).click();
    await page.getByRole('link',{name:'Rowan',exact:true}).click();
    await page.getByRole('button',{name:'Edit instructions'}).click();
    const definition = page.getByLabel('Instructions for Rowan’s future work');
    await definition.fill('Preserve source coverage.');
    const reporter = store.reporting.assignment(prior.dm);
    store.reporting.revise(reporter.agentId,'Include evidence.',prior.run);
    await page.getByRole('button',{name:'Save revision'}).click();
    await expect(page.getByRole('alert')).toContainText('definition has changed');
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.getByRole('button',{name:'Edit instructions'}).click();
    await expect(definition).toHaveValue('Include evidence.');
    await definition.fill('Preserve source coverage.');
    await page.getByRole('button',{name:'Save revision'}).click();
    await expect(page.getByText('Revision history · Revision 3')).toBeVisible();
    await page.screenshot({path:info.outputPath('agent.png')});
    await page.getByText('Revision history · Revision 3').click();
    await expect(page.locator('.revisions li')).toHaveCount(3);
    await page.getByRole('button',{name:'Rowan',exact:true}).click();
    await page.getByRole('button',{name:'Reply to report'}).click();
    await page.getByLabel('Message Rowan',{exact:true}).fill('Which sources were available?');
    await page.setViewportSize({width:360,height:780});
    await page.getByRole('link',{name:'Agent settings',exact:true}).click();
    await expect(page.getByText('Preserve source coverage.',{exact:true}).first()).toBeVisible();
    await page.getByRole('link',{name:'Usage reporting assignment'}).click();
    await expect(page.getByText('Report Codex and Claude usage and source coverage.')).toBeVisible();
    await page.getByRole('button',{name:'Schedule daily reports'}).click();
    await page.getByLabel('Daily time').fill('08:00');
    await page.getByRole('button',{name:'Review change'}).click();
    await page.getByRole('button',{name:'Allow recurring reports'}).click();
    await expect(page.getByText('Daily at 08:00 · America/Los_Angeles')).toBeVisible();
    await page.getByRole('button',{name:'Change schedule'}).click();
    await page.getByLabel('Daily time').fill('09:00');
    await page.getByRole('button',{name:'Review change'}).click();
    await expect(page.getByText('Daily at 08:00 · America/Los_Angeles')).toBeVisible();
    await page.getByRole('button',{name:'Open Rowan’s DM'}).click();
    await expect(page.getByLabel('Message Rowan',{exact:true})).toHaveValue('Which sources were available?');
    await expect(page.getByText(/Replying to the report for/)).toBeVisible();
    await page.getByRole('button',{name:'Allow recurring reports'}).click();
    const schedule = page.locator('header').getByRole('link',{name:'Assignment settings'});
    await expect(schedule).toContainText('09:00');
    await schedule.click();
    await page.reload();
    await expect(page.getByText('Daily at 09:00 · America/Los_Angeles')).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
    await page.screenshot({path:info.outputPath('assignment-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Back to conversation'}).click();
    await page.getByRole('article').getByRole('link',{name:'Assignment settings'}).click();
    page.once('dialog', dialog=>dialog.accept());
    await page.getByRole('button',{name:'Close reporting assignment'}).click();
    await expect(page.getByText('Access ended when this assignment closed.')).toBeVisible();
    expect(store.reporting.assignment(prior.dm).closed).toBe(1);
  } finally {await app.close();store.close();rmSync(root,{recursive:true,force:true});}
});
